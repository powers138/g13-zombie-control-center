def get_glyph(
    character: str,
) -> tuple[int, ...]:
    if not character:
        return GLYPHS["?"]

    normalized = character.upper()

    return GLYPHS.get(
        normalized,
        GLYPHS["?"],
    )


def text_width(text: str) -> int:
    return len(text) * FONT_ADVANCE
